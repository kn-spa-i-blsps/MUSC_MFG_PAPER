"""Amendment-16: robust-margin frontier (Part 1), gate-width diagnostic (Part 2), §8 viz + CBF wiring check (Part 3).
Base = amend15 cell s=1.05 (experiments/amend15_cells/s1.05.yaml). No controller code change; the scenario gains an
optional gate_width override (default None = GATE_RATIO * W0, so every earlier config and cache key is unchanged).
D_COLLISION is an analysis parameter (--d_collision). No verdict is computed except the pre-registered Part 3
CBF-engaged flag.

    python -m experiments.amend16_gate_diagnostic write-cells     # experiments/amend16_cells/{p1_d*,p2_g*,p3_*}.yaml
    python -m experiments.amend16_gate_diagnostic geometry
    python -m experiments.amend16_gate_diagnostic solve --cells p2_g1.50 [...]   # Phi / m* into results/cache
    python -m experiments.amend16_gate_diagnostic cbf-check       # Part 3 logs -> cbf_check.json (+ LOUD on bypass)
    python -m experiments.amend16_gate_diagnostic render          # Part 3 GIF animations (§8)
    python -m experiments.amend16_gate_diagnostic report [--d_collision 0.30] [--seeds 0 1 2 3 4]

Part 1 cells reuse the amend15 s=1.05 Phi/m* cache (d_safe is not in the cache key). Rollouts:
    python -m experiments.ladder --config experiments/amend16_cells/<cell>.yaml --mode eval --arm <arm>
        --weights results/ladder_fargoal_N100/predictor_weights.npz --seeds <seed>
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os

import numpy as np
import yaml

from experiments.amend15_density_sweep import WEIGHTS, WEIGHTS_SHA256, ci, safe_success
from experiments.smoke import ROOT, build_scenario, horizon_for

BASE = os.path.join(ROOT, "experiments", "amend15_cells", "s1.05.yaml")
CELL_DIR = os.path.join(ROOT, "experiments", "amend16_cells")
RUN = "amend16_gate_diagnostic_N100"
RES = os.path.join(ROOT, "results", RUN)
AMEND15_S105 = "results/density_sweep_amend15_N100/s1.05"
D_SAFES = [0.55, 0.90, 1.30, 1.90]
GATES = [1.5, 2.3, 3.5, 5.0, 7.0]
P2_ARMS = ["real", "learned"]
P3 = {"real": ("real", 0.55), "real_robust_d1.90": ("real", 1.90), "learned": ("learned", 0.55)}  # name: (arm, d_safe)
METRICS = ("safe_success", "completeness", "ever_collided", "p5_sep_worst_step_m", "cbf_intervention_rate",
           "slack_active_rate", "closedloop_xhat_mse_near")


def base_cfg():
    return copy.deepcopy(yaml.safe_load(open(BASE)))


def cells():
    """name -> cfg. p1: real_robust d_safe sweep (scenario identical to s1.05 -> same cache); p2: gate sweep;
    p3: viz rollouts with log_xhat."""
    out = {}
    for d in D_SAFES:
        c = base_cfg()
        c["cbf"]["d_safe"] = d
        c["run_name"] = f"{RUN}/p1/d{d:.2f}"
        out[f"p1_d{d:.2f}"] = c
    for g in GATES:
        c = base_cfg()
        c["scenario"]["gate_width"] = g
        c["run_name"] = f"{RUN}/p2/g{g:.2f}"
        out[f"p2_g{g:.2f}"] = c
    for name, (_, d) in P3.items():
        c = base_cfg()
        c["cbf"]["d_safe"] = d
        c["log_xhat"] = True
        c["run_name"] = f"{RUN}/p3/{name}"
        out[f"p3_{name}"] = c
    return out


def load_cell(name):
    return yaml.safe_load(open(os.path.join(CELL_DIR, f"{name}.yaml")))


def cmd_write_cells(a):
    os.makedirs(CELL_DIR, exist_ok=True)
    for name, cfg in cells().items():
        p = os.path.join(CELL_DIR, f"{name}.yaml")
        with open(p, "w") as f:
            f.write(f"# AMEND16 cell {name}: generated by experiments/amend16_gate_diagnostic.py from "
                    f"amend15_cells/s1.05.yaml (run_name + cbf.d_safe / scenario.gate_width / log_xhat)\n")
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(p)


def geometry(cfg):
    sc = build_scenario(cfg, cfg["N"])
    return {"gate_width": sc.gate_width, "d_safe": cfg["cbf"]["d_safe"], "r_goal": sc.r_goal, "arena": list(sc.arena),
            "H0_source_chamber": sc.H0, "wall_x": sc.wall_x, "gate_z": sc.gate_z, "goal_xz": list(sc.goal),
            "path_length": sc.path_length_to_goal(), "horizon_s": horizon_for(cfg, sc),
            "gate_inside_source_chamber": bool(sc.gate_width <= sc.H0)}


def cmd_geometry(a):
    g = {n: geometry(c) for n, c in cells().items()}
    base = geometry(base_cfg())
    pinned = ["arena", "wall_x", "gate_z", "goal_xz", "path_length", "horizon_s", "r_goal"]
    out = {"base_s1.05": base, "cells": g,
           "pinned_identical_to_base": {k: all(x[k] == base[k] for x in g.values()) for k in pinned}}
    print(json.dumps(out, indent=1))
    return out


def cmd_solve(a):
    import time
    from experiments.ladder import setup                     # imports jax; not needed by the analysis commands
    for name in a.cells:
        cfg = load_cell(name)
        t0 = time.time()
        _, grid, sol, _, path = setup(cfg)
        print(json.dumps({"cell": name, "cache": os.path.relpath(path, ROOT), "wall_s_this_call": time.time() - t0,
                          "solve_seconds": float(sol["solve_seconds"]), "horizon_s": grid.horizon,
                          "cesaro_converged": bool(sol["cesaro_converged"]), "iters": int(sol["iters"]),
                          "nan": bool(sol["nan"])}), flush=True)


def run_rows(run_dir, sc, seeds, d_collision):
    rows = []
    for seed in seeds:
        z = np.load(os.path.join(run_dir, f"logs_seed{seed}.npz"))
        m = json.load(open(os.path.join(run_dir, f"metrics_seed{seed}.json")))
        f = safe_success({"pos": z["pos"].astype(np.float64), "pos_final": z["pos_final"].astype(np.float64)},
                         sc, d_collision)
        f.update({k: m[k] for k in METRICS[3:]})
        f["macro_cache"] = m["macro_cache"]
        assert abs(f["completeness"] - m["completeness_final"]) < 1e-9
        rows.append(f)
    return {k: ci([r[k] for r in rows]) for k in METRICS} | {"macro_cache": sorted({r["macro_cache"] for r in rows})}


# ---------------------------------------------------------------- Part 3: CBF wiring check (pre-registered, §3)
def cbf_check_one(name, arm, d_safe, alt_d_safe, n_replay=200):
    import jax
    import jax.numpy as jnp
    from control.cbf import CBFParams, cbf_filter, init_warm_start
    from control.params import D_COLLISION

    cfg = load_cell(f"p3_{name}")
    sc = build_scenario(cfg, cfg["N"])
    z = np.load(os.path.join(ROOT, "results", cfg["run_name"], arm, "logs_seed0.npz"))
    pos = z["pos"].astype(np.float64)                                    # (T,N,2)
    xr = z["xhat_rel"].astype(np.float64)                                # (T,N,N,2) x_hat - own pos
    nb = z["cbf_nb_idx"].astype(np.int64)                                # (T,N,k)
    interv, qp_iters, rowv = z["intervention"], z["qp_iters"], z["row_violation"]
    u_log, u_nom = z["u"].astype(np.float64), z["u_nom"].astype(np.float64)
    T, N = pos.shape[:2]
    prm_cfg = cfg["cbf"]
    assert abs(prm_cfg["d_safe"] - d_safe) < 1e-12
    est_d_nb = np.linalg.norm(np.take_along_axis(xr, nb[..., None], axis=2), axis=-1)   # (T,N,k) est dist to nb
    valid = est_d_nb < prm_cfg["r_sense"]
    out = {"cell": name, "arm": arm, "d_safe_config": d_safe, "steps": T, "N": N,
           "frac_agent_steps_neighbour_set_nonempty": float(valid.any(-1).mean()),
           "mean_valid_neighbour_rows": float(valid.sum(-1).mean()),
           "frac_agent_steps_est_neighbour_inside_d_safe": float((valid & (est_d_nb < d_safe)).any(-1).mean()),
           "cbf_intervention_rate": float((interv > 0.01).mean()),
           "qp_nan_fallbacks": int((qp_iters < 0).sum()), "row_violation_max": float(rowv.max())}

    # replay: re-run the CBF filter on logged (positions, x_hat, u_nom) at n_replay steps with the config d_safe and
    # with alt_d_safe; the logged u must match the own-d_safe replay (x_hat logged as float16 -> small residual)
    segs = jnp.asarray(sc.wall_segments())
    ks = np.linspace(0, T - 1, n_replay).astype(int)

    def replay(ds):
        prm = CBFParams(**{**prm_cfg, "d_safe": ds})
        init = init_warm_start(N, prm, segs.shape[0])
        f = jax.jit(lambda p, xh, un: cbf_filter(p, xh, un, jnp.asarray(sc.goal), tuple(sc.arena), segs, init, prm)[0])
        return np.stack([np.asarray(f(jnp.asarray(pos[k]), jnp.asarray(pos[k][:, None] + xr[k]),
                                      jnp.asarray(u_nom[k]))) for k in ks])

    u_own, u_alt = replay(d_safe), replay(alt_d_safe)
    u_nom_box = np.clip(u_nom[ks], -prm_cfg["u_box"], prm_cfg["u_box"])
    act = interv[ks] > 0.01
    err = lambda u: float(np.linalg.norm(u - u_log[ks], axis=-1)[act].mean()) if act.any() else None
    out["replay"] = {"n_steps": int(n_replay), "intervened_agent_steps": int(act.sum()),
                     "mean_err_vs_logged_u_own_d_safe": err(u_own), "alt_d_safe": alt_d_safe,
                     "mean_err_vs_logged_u_alt_d_safe": err(u_alt),
                     "mean_err_vs_logged_u_no_cbf(u_nom_box)": err(u_nom_box),
                     "max_err_own_all_agents": float(np.linalg.norm(u_own - u_log[ks], axis=-1).max())}

    # true collision events: was the partner in the QP neighbour set, and what did the agent estimate?
    iu, ju = np.triu_indices(N, 1)
    ev = []
    for k in range(T):
        d = np.linalg.norm(pos[k, iu] - pos[k, ju], axis=-1)
        for p in np.where(d < D_COLLISION)[0]:
            for i, j in ((iu[p], ju[p]), (ju[p], iu[p])):
                in_nb = bool((nb[k, i] == j).any())
                ed = float(np.linalg.norm(xr[k, i, j]))
                ev.append((float(d[p]), ed, in_nb, in_nb and ed < prm_cfg["r_sense"]))
    if ev:
        e = np.array(ev)
        out["collision_agent_steps"] = {"n": len(ev), "frac_partner_in_neighbour_set": float(e[:, 2].mean()),
                                        "frac_partner_valid_row": float(e[:, 3].mean()),
                                        "frac_est_dist_ge_d_safe": float((e[:, 1] >= d_safe).mean()),
                                        "true_d_median": float(np.median(e[:, 0])),
                                        "est_d_median": float(np.median(e[:, 1])),
                                        "est_minus_true_median": float(np.median(e[:, 1] - e[:, 0]))}
    else:
        out["collision_agent_steps"] = {"n": 0}
    r = out["replay"]
    out["cbf_engaged"] = bool(out["frac_agent_steps_neighbour_set_nonempty"] > 0 and out["cbf_intervention_rate"] > 0
                              and out["qp_nan_fallbacks"] == 0 and r["mean_err_vs_logged_u_own_d_safe"] is not None
                              and r["mean_err_vs_logged_u_own_d_safe"]
                              < 0.1 * r["mean_err_vs_logged_u_no_cbf(u_nom_box)"]
                              and r["mean_err_vs_logged_u_own_d_safe"] < r["mean_err_vs_logged_u_alt_d_safe"])
    return out


def cmd_cbf_check(a):
    out = {}
    for name, (arm, d) in P3.items():
        out[name] = cbf_check_one(name, arm, d, 1.90 if d < 1.0 else 0.55)
        print(json.dumps(out[name], indent=1), flush=True)
    bypass = [n for n, o in out.items() if not o["cbf_engaged"]]
    out["cbf_bypassed_runs"] = bypass
    os.makedirs(RES, exist_ok=True)
    json.dump(out, open(os.path.join(RES, "cbf_check.json"), "w"), indent=1)
    if bypass:
        print("\n" + "!" * 80 + f"\n!!! CBF NOT ENGAGED / BYPASSED in {bypass} -> WIRING ARTIFACT: amend15 baseline rows "
              "must be quarantined (prereg amend16 §3)\n" + "!" * 80, flush=True)
    else:
        print("\nCBF engaged in every Part 3 run (neighbour set non-empty, interventions, QP solved, replay matches "
              "the config d_safe)", flush=True)
    return out


def cmd_render(a):
    from env.rollout import summarize
    from mfg.equilibrium import load_macro
    from viz import render
    os.makedirs(os.path.join(RES, "p3_viz"), exist_ok=True)
    for name, (arm, d) in P3.items():
        cfg = load_cell(f"p3_{name}")
        sc = build_scenario(cfg, cfg["N"])
        run_dir = os.path.join(ROOT, "results", cfg["run_name"], arm)
        z = dict(np.load(os.path.join(run_dir, "logs_seed0.npz")))
        m = json.load(open(os.path.join(run_dir, "metrics_seed0.json")))
        macro = load_macro(os.path.join(ROOT, m["macro_cache"]))
        _, series = summarize(z, sc, cfg["dt_exec"], c_w=1.0)
        path = os.path.join(RES, "p3_viz", f"{name}_seed0.gif")
        n = render.animate(path, sc, z, series, macro, dt_exec=cfg["dt_exec"], frame_dt=0.5,
                           title=f"amend16 §8 {name} seed 0  s=1.05 gate={sc.gate_width:.3f} d_safe={d:.2f}  "
                                 f"(orange = CBF active |u-u_nom|>0.01, red x = true d<0.30)")
        print(f"{path}: {n} frames", flush=True)


def cmd_report(a):
    with open(os.path.join(ROOT, WEIGHTS), "rb") as f:
        sha = hashlib.sha256(f.read()).hexdigest()
    base_sc = build_scenario(base_cfg(), 100)
    out = {"d_collision": a.d_collision, "seeds": a.seeds, "weights": WEIGHTS, "weights_sha256": sha,
           "weights_sha256_matches_record": sha == WEIGHTS_SHA256, "geometry": cmd_geometry(a),
           "part1_robust_margin": {}, "part1_reference_amend15": {}, "part2_gate_width": {}}
    for d in D_SAFES:
        cfg = load_cell(f"p1_d{d:.2f}")
        out["part1_robust_margin"][f"{d:.2f}"] = run_rows(os.path.join(ROOT, "results", cfg["run_name"], "real"),
                                                          base_sc, a.seeds, a.d_collision)
    for arm in ("real", "learned"):
        out["part1_reference_amend15"][f"{arm}@0.55"] = run_rows(os.path.join(ROOT, AMEND15_S105, arm), base_sc,
                                                                 a.seeds, a.d_collision)
    for g in GATES:
        cfg = load_cell(f"p2_g{g:.2f}")
        sc = build_scenario(cfg, cfg["N"])
        out["part2_gate_width"][f"{g:.2f}"] = {arm: run_rows(os.path.join(ROOT, "results", cfg["run_name"], arm), sc,
                                                             a.seeds, a.d_collision) for arm in P2_ARMS}
    # identity check (migration): p1 d0.55 is the amend15 real s=1.05 config, re-run on a re-solved cache
    ids = {}
    for seed in a.seeds:
        m16 = json.load(open(os.path.join(ROOT, "results", load_cell("p1_d0.55")["run_name"], "real",
                                          f"metrics_seed{seed}.json")))
        m15 = json.load(open(os.path.join(ROOT, AMEND15_S105, "real", f"metrics_seed{seed}.json")))
        ids[seed] = {k: [m15[k], m16[k]] for k in ("completeness_final", "collision_pair_steps", "min_sep_overall_m",
                                                   "p5_sep_worst_step_m")}
    out["identity_p1_d0.55_vs_amend15_real"] = {"per_seed_[amend15,amend16]": ids,
                                                "all_equal": all(v[0] == v[1] for r in ids.values() for v in r.values())}
    p = os.path.join(RES, "cbf_check.json")
    out["part3_cbf_check"] = json.load(open(p)) if os.path.exists(p) else None
    os.makedirs(RES, exist_ok=True)
    json.dump(out, open(os.path.join(RES, "report.json"), "w"), indent=1)

    fmt = lambda x: f"{x['mean']:>7.3f} [{x['ci95'][0]:.3f},{x['ci95'][1]:.3f}]"
    keys = ("safe_success", "completeness", "ever_collided", "p5_sep_worst_step_m")
    print("\nPART 1 real_robust (mean [95% seed-bootstrap CI])\n" + f"{'row':16s}" + "".join(f"{k:>24s}" for k in keys))
    for d, r in out["part1_robust_margin"].items():
        print(f"{'d_safe ' + d:16s}" + "".join(f"{fmt(r[k]):>24s}" for k in keys))
    for n, r in out["part1_reference_amend15"].items():
        print(f"{'ref ' + n:16s}" + "".join(f"{fmt(r[k]):>24s}" for k in keys))
    keys2 = keys + ("closedloop_xhat_mse_near",)
    print("\nPART 2 gate width\n" + f"{'row':16s}" + "".join(f"{k:>26s}" for k in keys2))
    for g, arms in out["part2_gate_width"].items():
        for arm, r in arms.items():
            print(f"{'g' + g + ' ' + arm:16s}" + "".join(f"{fmt(r[k]):>26s}" for k in keys2))
    c = out["part3_cbf_check"]
    print("\nPART 3 cbf_engaged:", {n: c[n]["cbf_engaged"] for n in P3} if c else None,
          "bypassed:", c["cbf_bypassed_runs"] if c else None)
    print("identity p1 d0.55 == amend15 real:", out["identity_p1_d0.55_vs_amend15_real"]["all_equal"])
    print("weights sha256:", sha, "matches record:", sha == WEIGHTS_SHA256)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["write-cells", "geometry", "solve", "cbf-check", "render", "report"])
    ap.add_argument("--d_collision", type=float, default=0.30)
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    ap.add_argument("--cells", nargs="+", default=[f"p2_g{g:.2f}" for g in GATES])
    a = ap.parse_args()
    {"write-cells": cmd_write_cells, "geometry": cmd_geometry, "solve": cmd_solve, "cbf-check": cmd_cbf_check,
     "render": cmd_render, "report": cmd_report}[a.cmd](a)


if __name__ == "__main__":
    main()
