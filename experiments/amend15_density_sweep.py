"""Amendment-15: density sweep over the goal hex spacing s on a PINNED geometry (scenario.goal_geometry_spacing
1.05: goal x-offset, arena and path length / horizon fixed for every cell; only r_goal = 5.25 s varies).
d_safe 0.55 for every arm; D_COLLISION is an analysis parameter (--d_collision). No verdict is computed.

    python -m experiments.amend15_density_sweep geometry            # pinned dims per cell (no solve)
    python -m experiments.amend15_density_sweep integrity           # amend11 logs: learned safe success ~0.168
    python -m experiments.amend15_density_sweep write-cells         # experiments/amend15_cells/s<s>.yaml
    python -m experiments.amend15_density_sweep solve --cells 0.45 [...]   # Phi / m* per cell into results/cache
    python -m experiments.amend15_density_sweep report [--d_collision 0.30] [--seeds 0 1 2 3 4]

Rollouts: python -m experiments.ladder --config experiments/amend15_cells/s<s>.yaml --mode eval --arm <arm>
    --weights results/ladder_fargoal_N100/predictor_weights.npz --seeds <seed>   (after the cell's solve).
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
import os
import time

import numpy as np
import yaml

from experiments.ladder_report import boot_ci
from experiments.smoke import ROOT, build_scenario, horizon_for

BASE = os.path.join(ROOT, "experiments", "density_sweep_amend15.yaml")
CELL_DIR = os.path.join(ROOT, "experiments", "amend15_cells")
SPACINGS = [0.45, 0.60, 0.75, 0.90, 1.05]
ARMS = ["real", "cv", "learned", "smith"]
WEIGHTS = "results/ladder_fargoal_N100/predictor_weights.npz"
WEIGHTS_SHA256 = "fc4a52a582688a9927f252e8d11d45420796c2b5a3c82fe1ed535d55d447417e"   # amend6 record, used in amend11
AMEND11 = "results/ladder_fargoal_amend11_N100"
INTEGRITY_REF, INTEGRITY_TOL = 0.168, 0.05


def cell_cfg(s):
    cfg = yaml.safe_load(open(BASE))
    cfg = copy.deepcopy(cfg)
    cfg["scenario"]["goal_spacing"] = s
    cfg["run_name"] = f"{cfg['run_name']}/s{s:.2f}"
    return cfg


def geometry(s):
    cfg = cell_cfg(s)
    sc = build_scenario(cfg, cfg["N"])
    return {"goal_spacing": s, "rho_hex": 2.0 / (math.sqrt(3.0) * s ** 2), "r_goal": sc.r_goal, "r_geom": sc.r_geom,
            "arena_W": sc.arena[0], "arena_H": sc.arena[1], "wall_x": sc.wall_x, "gate_z": sc.gate_z,
            "gate_width": sc.gate_width, "goal_xz": list(sc.goal), "z_off": sc.z_off, "start_box": list(sc.start_box),
            "path_length": sc.path_length_to_goal(), "horizon_s": horizon_for(cfg, sc),
            "disc_inside_arena": bool(sc.goal[0] + sc.r_goal <= sc.arena[0] and sc.goal[1] - sc.r_goal >= 0
                                      and sc.goal[1] + sc.r_goal <= sc.arena[1])}


def cmd_geometry(a):
    g = [geometry(s) for s in SPACINGS]
    pinned = ["arena_W", "arena_H", "wall_x", "gate_z", "goal_xz", "z_off", "start_box", "path_length", "horizon_s"]
    same = {k: all(x[k] == g[0][k] for x in g) for k in pinned}
    out = {"cells": g, "pinned_identical_across_cells": same}
    print(json.dumps(out, indent=1))
    return out


def cmd_integrity(a):
    cfg = yaml.safe_load(open(os.path.join(ROOT, "experiments", "ladder_fargoal_amend11.yaml")))
    sc = build_scenario(cfg, cfg["N"])
    v = []
    for s in a.seeds11:
        z = np.load(os.path.join(ROOT, AMEND11, "learned", f"logs_seed{s}.npz"))
        z = {"pos": z["pos"].astype(np.float64), "pos_final": z["pos_final"].astype(np.float64)}
        v.append(safe_success(z, sc, a.d_collision)["safe_success"])
    m = float(np.mean(v))
    out = {"source": AMEND11 + "/learned", "seeds": a.seeds11, "d_collision": a.d_collision, "per_seed": v,
           "mean": m, "reference": INTEGRITY_REF, "abs_diff": abs(m - INTEGRITY_REF),
           "pass": abs(m - INTEGRITY_REF) <= INTEGRITY_TOL}
    print(json.dumps(out, indent=1))
    return out


def safe_success(z, sc, d_collision):
    pos = np.concatenate([z["pos"], z["pos_final"][None]], 0)
    T1, N, _ = pos.shape
    iu, ju = np.triu_indices(N, 1)
    collided = np.zeros(N, bool)
    for t0 in range(0, T1, 1000):
        hit = (np.linalg.norm(pos[t0:t0 + 1000, iu] - pos[t0:t0 + 1000, ju], axis=-1) < d_collision).any(0)
        collided[iu[hit]] = True
        collided[ju[hit]] = True
    arrived = np.linalg.norm(pos[-1] - np.asarray(sc.goal), axis=-1) <= sc.r_goal
    return {"safe_success": float((arrived & ~collided).mean()), "completeness": float(arrived.mean()),
            "ever_collided": float(collided.mean())}


def cmd_write_cells(a):
    os.makedirs(CELL_DIR, exist_ok=True)
    for s in SPACINGS:
        cfg = cell_cfg(s)
        p = os.path.join(CELL_DIR, f"s{s:.2f}.yaml")
        with open(p, "w") as f:
            f.write(f"# AMEND15 cell s={s:.2f}: generated by experiments/amend15_density_sweep.py from "
                    f"density_sweep_amend15.yaml (goal_spacing, run_name)\n")
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(p)


def cmd_solve(a):
    from experiments.ladder import setup                     # imports jax; not needed by the analysis commands
    for s in a.cells:
        cfg = yaml.safe_load(open(os.path.join(CELL_DIR, f"s{s:.2f}.yaml")))
        t0 = time.time()
        _, grid, sol, _, path = setup(cfg)
        print(json.dumps({"cell": s, "cache": os.path.relpath(path, ROOT), "wall_s_this_call": time.time() - t0,
                          "solve_seconds": float(sol["solve_seconds"]), "horizon_s": grid.horizon,
                          "cesaro_converged": bool(sol["cesaro_converged"]), "iters": int(sol["iters"]),
                          "nan": bool(sol["nan"])}), flush=True)


def ci(v):
    v = np.asarray(v, float)
    lo, hi = boot_ci(v)
    return {"mean": float(v.mean()), "sd": float(v.std(ddof=1)) if v.size > 1 else None, "ci95": [lo, hi],
            "per_seed": v.tolist()}


def cmd_report(a):
    with open(os.path.join(ROOT, WEIGHTS), "rb") as f:
        sha = hashlib.sha256(f.read()).hexdigest()
    out = {"d_collision": a.d_collision, "seeds": a.seeds, "weights": WEIGHTS, "weights_sha256": sha,
           "weights_sha256_matches_record": sha == WEIGHTS_SHA256, "geometry": cmd_geometry(a),
           "integrity": cmd_integrity(a), "cells": {}}
    for s in SPACINGS:
        cfg = yaml.safe_load(open(os.path.join(CELL_DIR, f"s{s:.2f}.yaml")))
        sc = build_scenario(cfg, cfg["N"])
        run_dir = os.path.join(ROOT, "results", cfg["run_name"])
        out["cells"][f"{s:.2f}"] = {}
        for arm in ARMS:
            rows = []
            for seed in a.seeds:
                z = np.load(os.path.join(run_dir, arm, f"logs_seed{seed}.npz"))
                m = json.load(open(os.path.join(run_dir, arm, f"metrics_seed{seed}.json")))
                f = safe_success({"pos": z["pos"].astype(np.float64),
                                  "pos_final": z["pos_final"].astype(np.float64)}, sc, a.d_collision)
                f.update({k: m[k] for k in ("p5_sep_worst_step_m", "cbf_intervention_rate", "slack_active_rate",
                                            "completeness_final", "closedloop_xhat_mse_near")})
                assert abs(f["completeness"] - m["completeness_final"]) < 1e-9
                rows.append(f)
            out["cells"][f"{s:.2f}"][arm] = {k: ci([r[k] for r in rows]) for k in
                                             ("safe_success", "completeness", "ever_collided", "p5_sep_worst_step_m",
                                              "cbf_intervention_rate", "slack_active_rate",
                                              "closedloop_xhat_mse_near")}
    # consistency (2): amend13 learned safe success at c=0.15, s=0.80 (margin s-c=0.65) vs cells s=0.90 / 1.05 at c
    a13 = json.load(open(os.path.join(ROOT, AMEND11, "amend13_threshold_curve.json")))
    ref = a13["summary"]["learned"]["0.15"]["safe_success"]["mean"]
    lo, hi = (out["cells"][k]["learned"]["safe_success"]["mean"] for k in ("0.90", "1.05"))
    out["consistency_margin_0.65"] = {"amend13_learned_c0.15_s0.80": ref, "learned_s0.90": lo, "learned_s1.05": hi,
                                      "between": min(lo, hi) <= ref <= max(lo, hi)}
    res = os.path.join(ROOT, "results", yaml.safe_load(open(BASE))["run_name"])
    os.makedirs(res, exist_ok=True)
    json.dump(out, open(os.path.join(res, "amend15_report.json"), "w"), indent=1)
    for key in ("safe_success", "completeness", "ever_collided", "p5_sep_worst_step_m", "cbf_intervention_rate",
                "slack_active_rate"):
        print(f"\n{key} (mean [95% seed-bootstrap CI])\n{'arm':8s}" + "".join(f"{f's={s:.2f}':>22s}" for s in SPACINGS))
        for arm in ARMS:
            c = [out["cells"][f"{s:.2f}"][arm][key] for s in SPACINGS]
            print(f"{arm:8s}" + "".join(f"{x['mean']:>8.3f} [{x['ci95'][0]:.3f},{x['ci95'][1]:.3f}]" for x in c))
    print("\nconsistency (2):", out["consistency_margin_0.65"])
    print("weights sha256:", sha, "matches record:", sha == WEIGHTS_SHA256)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["geometry", "integrity", "write-cells", "solve", "report"])
    ap.add_argument("--d_collision", type=float, default=0.30)
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    ap.add_argument("--seeds11", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    ap.add_argument("--cells", type=float, nargs="+", default=SPACINGS)
    a = ap.parse_args()
    {"geometry": cmd_geometry, "integrity": cmd_integrity, "write-cells": cmd_write_cells, "solve": cmd_solve,
     "report": cmd_report}[a.cmd](a)


if __name__ == "__main__":
    main()
