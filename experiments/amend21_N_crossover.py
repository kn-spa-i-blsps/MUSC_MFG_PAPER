"""Amendment-21: N crossover on ONE fixed geometry, precision=highest. N in {25, 50, 100, 150, 200}; arms real (fixed
d_safe 0.55), learned fixed d_safe 0.70, learned closing k=0.75 (floor 0.55, h=0.3); seeds 0-9.
Geometry (PI decisions 2026-10-23, logged in INDEX): scenario.geometry_N = 230 (amend15 s=1.05 scenario keys, standard
scaling; the smallest of {200,220,230,...} giving N=200 a min initial separation >= 0.55 over seeds 0-9), gate pinned at
the amend15-20 value 2.309 (gate_width override). Phi/m* solved once PER N on that geometry (m0 has mass N and the
congestion cost uses an absolute m_bar, so Phi/m* depend on the agent count); all three arms of one N share it.
T_frame = N * T_SLOT (T_SLOT = 0.005). CIs: seed-level (cluster) bootstrap.

    python -m experiments.amend21_N_crossover write-cells    # experiments/amend21_cells/N*_*.yaml
    python -m experiments.amend21_N_crossover geometry       # dims + min initial separation per N (seeds 0-9)
    python -m experiments.amend21_N_crossover solve --N 25   # Phi/m* for that N into results/cache
    python -m experiments.amend21_N_crossover report [--d_collision 0.30] [--seeds 0 .. 9]
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os

import numpy as np
import yaml

from control.params import D_COLLISION, T_SLOT
from experiments.amend15_density_sweep import WEIGHTS, WEIGHTS_SHA256, ci, safe_success
from experiments.smoke import ROOT, build_scenario, horizon_for

BASE = os.path.join(ROOT, "experiments", "amend15_cells", "s1.05.yaml")
CELL_DIR = os.path.join(ROOT, "experiments", "amend21_cells")
RUN = "amend21_N_crossover"
RES = os.path.join(ROOT, "results", RUN)
ANEKS = os.path.join(ROOT, "prereg", "prereg_projectA_amend21_N_crossover.md")
NS = [25, 50, 100, 150, 200]
GEOMETRY_N = 230
GATE = 2.309401076758503                     # amend15-20 gate (gate_width_for_N(100))
ARMS = {"real": ("real", {"d_safe": 0.55}),
        "learned_fixed0.70": ("learned", {"d_safe": 0.70}),
        "learned_closing0.75": ("learned", {"d_safe": 0.55, "margin_k": 0.75, "margin_mode": "closing",
                                            "margin_floor": 0.55, "margin_h": 0.3})}
SEEDS = list(range(10))
METRICS = ("safe_success", "ever_collided", "completeness", "p5_sep_worst_step_m", "cbf_intervention_rate",
           "slack_active_rate", "closedloop_xhat_mse_near", "closedloop_xhat_mse_all")
MARGIN_METRICS = ("d_safe_mean", "d_safe_p50", "d_safe_p95", "v_closing_mean", "v_closing_p50", "v_closing_p95")


def cell_name(N, arm):
    return f"N{N:03d}_{arm}"


def cells():
    """name -> (arm, cfg)."""
    out = {}
    for N in NS:
        for arm, (cond, cbf) in ARMS.items():
            c = copy.deepcopy(yaml.safe_load(open(BASE)))
            c["N"] = N
            c["scenario"]["geometry_N"] = GEOMETRY_N
            c["scenario"]["gate_width"] = GATE
            c["cbf"].update(cbf)
            c["matmul_precision"] = "highest"
            c["run_name"] = f"{RUN}/N{N:03d}/{arm}"
            out[cell_name(N, arm)] = (cond, c)
    return out


def load_cell(name):
    return yaml.safe_load(open(os.path.join(CELL_DIR, f"{name}.yaml")))


def cmd_write_cells(a):
    os.makedirs(CELL_DIR, exist_ok=True)
    for name, (cond, cfg) in cells().items():
        p = os.path.join(CELL_DIR, f"{name}.yaml")
        with open(p, "w") as f:
            f.write(f"# AMEND21 cell {name} (condition {cond}): generated by experiments/amend21_N_crossover.py from "
                    f"amend15_cells/s1.05.yaml (N, scenario.geometry_N/gate_width, cbf, matmul_precision, run_name)\n")
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(p)


def cmd_geometry(a):
    import jax
    out = {"geometry_N": GEOMETRY_N, "gate_width": GATE, "T_SLOT": T_SLOT, "per_N": {}}
    for N in NS:
        cfg = load_cell(cell_name(N, "real"))
        sc = build_scenario(cfg, N)
        mins = []
        for seed in SEEDS:
            p = np.asarray(sc.initial_positions(jax.random.PRNGKey(seed)))
            d = np.linalg.norm(p[:, None] - p[None], axis=-1)
            d[np.arange(N), np.arange(N)] = np.inf
            mins.append(float(d.min()))
        g = {"arena": list(sc.arena), "gate_width": sc.gate_width, "wall_x": sc.wall_x, "gate_z": sc.gate_z,
             "goal_xz": list(sc.goal), "r_goal": sc.r_goal, "start_box": list(sc.start_box),
             "path_length": sc.path_length_to_goal(), "horizon_s": horizon_for(cfg, sc), "n_agents": sc.N,
             "T_frame_s": N * T_SLOT, "density_agents_per_free_m2": N / sc.free_area(),
             "min_initial_sep_seeds0_9": min(mins), "fits_without_overlap": min(mins) >= D_COLLISION,
             "min_initial_sep_ge_0.55": min(mins) >= 0.55}
        out["per_N"][str(N)] = g
    keys = ["arena", "gate_width", "wall_x", "gate_z", "goal_xz", "r_goal", "start_box", "path_length", "horizon_s"]
    first = out["per_N"][str(NS[0])]
    out["geometry_identical_across_N"] = {k: all(v[k] == first[k] for v in out["per_N"].values()) for k in keys}
    out["dropped_N"] = [N for N in NS if not out["per_N"][str(N)]["fits_without_overlap"]]
    print(json.dumps(out, indent=1))
    return out


def cmd_solve(a):
    import time
    from experiments.ladder import setup
    cfg = load_cell(cell_name(a.N, "real"))
    t0 = time.time()
    _, grid, sol, _, path = setup(cfg)
    print(json.dumps({"N": a.N, "cache": os.path.relpath(path, ROOT), "wall_s_this_call": time.time() - t0,
                      "solve_seconds": float(sol["solve_seconds"]), "horizon_s": grid.horizon,
                      "cesaro_converged": bool(sol["cesaro_converged"]), "iters": int(sol["iters"]),
                      "nan": bool(sol["nan"])}), flush=True)


def run_rows(rdir, sc, seeds, d_collision, margin):
    rows, prec = [], set()
    keys = METRICS + (MARGIN_METRICS if margin else ())
    for seed in seeds:
        z = np.load(os.path.join(rdir, f"logs_seed{seed}.npz"))
        m = json.load(open(os.path.join(rdir, f"metrics_seed{seed}.json")))
        f = safe_success({"pos": z["pos"].astype(np.float64), "pos_final": z["pos_final"].astype(np.float64)},
                         sc, d_collision)
        f.update({k: m[k] for k in keys[3:]})
        assert abs(f["completeness"] - m["completeness_final"]) < 1e-9
        prec.add(str(m.get("matmul_precision")))
        rows.append(f | {"macro_cache": m["macro_cache"]})
    return ({k: ci([r[k] for r in rows]) for k in keys}
            | {"macro_cache": sorted({r["macro_cache"] for r in rows}), "matmul_precision": sorted(prec)})


def sha256(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def cmd_report(a):
    sha = sha256(os.path.join(ROOT, WEIGHTS))
    out = {"d_collision": a.d_collision, "seeds": a.seeds, "geometry": cmd_geometry(a), "aneks_sha256": sha256(ANEKS),
           "deviation": "PI-ordered mid-run (2026-10-24): learned arms run only at N=100; N=25 learned rows are the rollouts that "
                        "ran before the stop; learned at N=50/150/200 not run (predictor fails off its training N=100, "
                        "logs/amend21_pod/ood_diagnostic.log)",
           "weights": WEIGHTS, "weights_sha256": sha, "weights_sha256_matches_record": sha == WEIGHTS_SHA256,
           "matmul_precision": "highest", "ci": "seed-level (cluster) bootstrap, 10k, 95%", "rows": {}}
    for N in NS:
        if N in out["geometry"]["dropped_N"]:
            continue
        sc = build_scenario(load_cell(cell_name(N, "real")), N)
        out["rows"][str(N)] = {}
        for arm, (cond, _) in ARMS.items():
            rdir = os.path.join(ROOT, "results", load_cell(cell_name(N, arm))["run_name"], cond)
            if not os.path.exists(os.path.join(rdir, f"metrics_seed{a.seeds[0]}.json")):
                continue          # PI mid-run deviation: learned arms only at N=100 (+ the N=25 rollouts that already ran)
            out["rows"][str(N)][arm] = run_rows(rdir, sc, a.seeds, a.d_collision, margin="closing" in arm)
    os.makedirs(RES, exist_ok=True)
    json.dump(out, open(os.path.join(RES, "report.json"), "w"), indent=1)

    fmt = lambda x: f"{x['mean']:.3f} [{x['ci95'][0]:.3f},{x['ci95'][1]:.3f}]"
    keys = METRICS + MARGIN_METRICS
    print(f"\nAMEND21 N crossover, geometry_N={GEOMETRY_N}, gate={GATE:.3f}, precision=highest, seeds {a.seeds}\n"
          + f"{'row':28s}" + "".join(f"{k:>26s}" for k in keys))
    for N, arms in out["rows"].items():
        for arm, r in arms.items():
            print(f"{'N=' + N + ' ' + arm:28s}" + "".join(f"{fmt(r[k]) if k in r else '—':>26s}" for k in keys))
    print("precision per row:", {f"{N}/{arm}": r["matmul_precision"] for N, arms in out["rows"].items()
                                 for arm, r in arms.items()})
    print("dropped N:", out["geometry"]["dropped_N"])
    print("aneks sha256:", out["aneks_sha256"])
    print("weights sha256:", sha, "matches record:", sha == WEIGHTS_SHA256)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["write-cells", "geometry", "solve", "report"])
    ap.add_argument("--d_collision", type=float, default=0.30)
    ap.add_argument("--seeds", type=int, nargs="+", default=SEEDS)
    ap.add_argument("--N", type=int)
    a = ap.parse_args()
    {"write-cells": cmd_write_cells, "geometry": cmd_geometry, "solve": cmd_solve, "report": cmd_report}[a.cmd](a)


if __name__ == "__main__":
    main()
