"""Amendment-19: closure-gated adaptive CBF margin (method v2a) on the learned arm at s=1.05 (gate 2.309).
CONTROLLER CHANGE (cbf.margin_mode = "closing"): d_safe_ij = max(0.55, D_COLLISION + k * max(0, v_closing_ij) * h),
h = 0.3 s, v_closing_ij = (v_i - v_hat_j) . e_ij (e_ij = unit vector from i to its estimate x_hat_ij of j; v_i = own
velocity from the last step; v_hat_j = FD of i's last two heard absolute positions of j). Base =
experiments/amend15_cells/s1.05.yaml; s=1.05 cache reused.

    python -m experiments.amend19_closing_margin write-cells   # experiments/amend19_cells/{k*,san_*}.yaml
    python -m experiments.amend19_closing_margin sanity        # k=0 vs fixed d_safe 0.55, seed 0 -> sanity_k0.json
    python -m experiments.amend19_closing_margin report [--d_collision 0.30] [--seeds 0 1 2 3 4]

Rollouts:
    python -m experiments.ladder --config experiments/amend19_cells/<cell>.yaml --mode eval --arm learned
        --weights results/ladder_fargoal_N100/predictor_weights.npz --seeds <seed>
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os

import numpy as np
import yaml

from experiments.amend15_density_sweep import WEIGHTS, WEIGHTS_SHA256, ci, safe_success
from experiments.smoke import ROOT, build_scenario

BASE = os.path.join(ROOT, "experiments", "amend15_cells", "s1.05.yaml")
CELL_DIR = os.path.join(ROOT, "experiments", "amend19_cells")
RUN = "amend19_closing_margin_N100"
RES = os.path.join(ROOT, "results", RUN)
ANEKS = os.path.join(ROOT, "prereg", "prereg_projectA_amend19_closing_margin.md")
AMEND18_REPORT = os.path.join(ROOT, "results", "amend18_fixed_margin_learned_N100", "report.json")
FLOOR, H = 0.55, 0.3
KS = [0.5, 1.0, 2.0]
SANITY_ARMS = ["learned", "real"]
METRICS = ("safe_success", "completeness", "ever_collided", "p5_sep_worst_step_m", "cbf_intervention_rate",
           "slack_active_rate", "d_safe_mean", "d_safe_p50", "d_safe_p95", "v_closing_mean", "v_closing_p50",
           "v_closing_p95", "v_closing_frac_zero_bin")
SANITY_KEYS = ("completeness_final", "collision_pair_steps", "min_sep_overall_m", "p5_sep_worst_step_m",
               "cbf_intervention_rate", "slack_active_rate")


def base_cfg():
    return copy.deepcopy(yaml.safe_load(open(BASE)))


def closing_cbf(k):
    return dict(margin_k=k, margin_mode="closing", margin_floor=FLOOR, margin_h=H)


def cells():
    out = {}
    for k in KS:
        c = base_cfg()
        c["cbf"].update(d_safe=FLOOR, **closing_cbf(k))
        c["run_name"] = f"{RUN}/k{k:.2f}"
        out[f"k{k:.2f}"] = c
    c = base_cfg()
    c["cbf"].update(d_safe=FLOOR, **closing_cbf(0.0))
    c["run_name"] = f"{RUN}/sanity/k0"
    out["san_k0"] = c
    c = base_cfg()                                   # = amend15 s=1.05 / amend18 d0.55 config (fixed d_safe 0.55)
    c["run_name"] = f"{RUN}/sanity/fixed0.55"
    out["san_fixed0.55"] = c
    return out


def load_cell(name):
    return yaml.safe_load(open(os.path.join(CELL_DIR, f"{name}.yaml")))


def cmd_write_cells(a):
    os.makedirs(CELL_DIR, exist_ok=True)
    for name, cfg in cells().items():
        p = os.path.join(CELL_DIR, f"{name}.yaml")
        with open(p, "w") as f:
            f.write(f"# AMEND19 cell {name}: generated by experiments/amend19_closing_margin.py from "
                    f"amend15_cells/s1.05.yaml (run_name + cbf.d_safe / margin_k / margin_mode / margin_floor / "
                    f"margin_h)\n")
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(p)


def run_dir(cell, arm):
    return os.path.join(ROOT, "results", load_cell(cell)["run_name"], arm)


def run_rows(rdir, sc, seeds, d_collision):
    rows, hist = [], None
    for seed in seeds:
        z = np.load(os.path.join(rdir, f"logs_seed{seed}.npz"))
        m = json.load(open(os.path.join(rdir, f"metrics_seed{seed}.json")))
        f = safe_success({"pos": z["pos"].astype(np.float64), "pos_final": z["pos_final"].astype(np.float64)},
                         sc, d_collision)
        f.update({k: m[k] for k in METRICS[3:]})
        f["macro_cache"] = m["macro_cache"]
        assert abs(f["completeness"] - m["completeness_final"]) < 1e-9
        h = np.asarray(m["v_closing_hist"], np.int64)
        hist = h if hist is None else hist + h
        rows.append(f)
    return ({k: ci([r[k] for r in rows]) for k in METRICS}
            | {"macro_cache": sorted({r["macro_cache"] for r in rows}),
               "v_closing_hist_all_seeds": hist.tolist(), "v_closing_hist_bin_mps": m["v_closing_hist_bin_mps"]})


def cmd_sanity(a):
    """k=0 (closing mode, d_safe = max(0.55, 0.30) = 0.55 on every row) vs fixed d_safe 0.55, seed 0: every logged
    array compared element-wise. Both run with XLA autotuning off (learned is not run-to-run deterministic on the GPU
    with autotuning on; amend18 post-hoc), so a mismatch can only come from the code."""
    out = {}
    for arm in SANITY_ARMS:
        za = np.load(os.path.join(run_dir("san_k0", arm), "logs_seed0.npz"))
        zb = np.load(os.path.join(run_dir("san_fixed0.55", arm), "logs_seed0.npz"))
        ma = json.load(open(os.path.join(run_dir("san_k0", arm), "metrics_seed0.json")))
        mb = json.load(open(os.path.join(run_dir("san_fixed0.55", arm), "metrics_seed0.json")))
        common = sorted(set(za.files) & set(zb.files))
        arr = {k: {"bit_equal": bool(np.array_equal(za[k], zb[k])),
                   "max_abs_diff": float(np.nanmax(np.abs(np.asarray(za[k], np.float64) - np.asarray(zb[k], np.float64))))
                   if za[k].size else 0.0} for k in common}
        h = np.asarray(za["d_safe_hist"]).sum(0)
        b055 = int(round((FLOOR - 0.30) / 0.01))
        out[arm] = {"arrays_compared": len(common), "only_in_k0": sorted(set(za.files) - set(zb.files)),
                    "all_common_arrays_bit_equal": all(v["bit_equal"] for v in arr.values()), "arrays": arr,
                    "metrics_[k0,fixed0.55]": {k: [ma[k], mb[k]] for k in SANITY_KEYS},
                    "k0_d_safe_rows_off_0.55_bin": int(h.sum() - h[b055]),
                    "k0_d_safe_mean_p50_p95": [ma["d_safe_mean"], ma["d_safe_p50"], ma["d_safe_p95"]]}
        print(arm, json.dumps({k: v for k, v in out[arm].items() if k != "arrays"}), flush=True)
    os.makedirs(RES, exist_ok=True)
    json.dump(out, open(os.path.join(RES, "sanity_k0.json"), "w"), indent=1)
    return out


def sha256(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def cmd_report(a):
    sha = sha256(os.path.join(ROOT, WEIGHTS))
    sc = build_scenario(base_cfg(), 100)
    r18 = json.load(open(AMEND18_REPORT))["fixed_margin_learned"]
    out = {"d_collision": a.d_collision, "seeds": a.seeds, "gate_width": sc.gate_width, "arm": "learned",
           "floor": FLOOR, "h_s": H, "aneks_sha256": sha256(ANEKS), "weights": WEIGHTS, "weights_sha256": sha,
           "weights_sha256_matches_record": sha == WEIGHTS_SHA256, "closing_margin_learned": {},
           "reference_rows_reused": {f"learned fixed {d} (amend18)": r18[d] for d in ("0.55", "0.70")}}
    for k in KS:
        out["closing_margin_learned"][f"{k:.2f}"] = run_rows(run_dir(f"k{k:.2f}", "learned"), sc, a.seeds,
                                                             a.d_collision)
    p = os.path.join(RES, "sanity_k0.json")
    out["sanity_k0"] = json.load(open(p)) if os.path.exists(p) else None
    os.makedirs(RES, exist_ok=True)
    json.dump(out, open(os.path.join(RES, "report.json"), "w"), indent=1)

    fmt = lambda x: "—" if x is None else f"{x['mean']:.3f} [{x['ci95'][0]:.3f},{x['ci95'][1]:.3f}]"
    print("\nAMEND19 closing margin, learned, s=1.05 (mean [95% seed-bootstrap CI])\n" + f"{'row':26s}"
          + "".join(f"{k:>24s}" for k in METRICS))
    for k, r in out["closing_margin_learned"].items():
        print(f"{'k=' + k:26s}" + "".join(f"{fmt(r[m]):>24s}" for m in METRICS))
    for n, r in out["reference_rows_reused"].items():
        print(f"{'ref ' + n:26s}" + "".join(f"{fmt(r.get(m)):>24s}" for m in METRICS))
    s = out["sanity_k0"]
    print("\nsanity k=0 all arrays bit-equal:", {arm: s[arm]["all_common_arrays_bit_equal"] for arm in s} if s else None)
    print("aneks sha256:", out["aneks_sha256"])
    print("weights sha256:", sha, "matches record:", sha == WEIGHTS_SHA256)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["write-cells", "sanity", "report"])
    ap.add_argument("--d_collision", type=float, default=0.30)
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    a = ap.parse_args()
    {"write-cells": cmd_write_cells, "sanity": cmd_sanity, "report": cmd_report}[a.cmd](a)


if __name__ == "__main__":
    main()
