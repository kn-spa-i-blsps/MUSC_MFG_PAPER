"""Amendment-20: closure-gated margin (amend19 method, unchanged) under jax_default_matmul_precision = "highest" (cell
key matmul_precision, applied globally in experiments/ladder.py and logged per run), k in {0.25, 0.50, 0.75} + learned
fixed d_safe {0.55, 0.70} re-run as apples-to-apples references + real fixed 0.55 (aneks §1: real re-run under highest),
seeds 0-9, s=1.05, gate 2.309; s=1.05 cache reused. CIs: seed-level (cluster) bootstrap, experiments.ladder_report.boot_ci.

    python -m experiments.amend20_closing_lockin write-cells   # experiments/amend20_cells/*.yaml
    python -m experiments.amend20_closing_lockin report [--d_collision 0.30] [--seeds 0 .. 9]

Rollouts:
    python -m experiments.ladder --config experiments/amend20_cells/<cell>.yaml --mode eval --arm <arm>
        --weights results/ladder_fargoal_N100/predictor_weights.npz --seeds <seed>
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os

import numpy as np
import yaml

from experiments.amend15_density_sweep import WEIGHTS, WEIGHTS_SHA256, ci, safe_success
from experiments.smoke import ROOT, build_scenario

BASE = os.path.join(ROOT, "experiments", "amend15_cells", "s1.05.yaml")
CELL_DIR = os.path.join(ROOT, "experiments", "amend20_cells")
RUN = "amend20_closing_lockin_N100"
RES = os.path.join(ROOT, "results", RUN)
ANEKS = os.path.join(ROOT, "prereg", "prereg_projectA_amend20_closing_lockin.md")
AMEND15_S105_REAL = os.path.join(ROOT, "results", "density_sweep_amend15_N100", "s1.05", "real")
PRECISION = "highest"
FLOOR, H = 0.55, 0.3
KS = [0.25, 0.50, 0.75]
FIXED = [0.55, 0.70]
SEEDS = list(range(10))
BASE_METRICS = ("safe_success", "completeness", "ever_collided", "p5_sep_worst_step_m", "cbf_intervention_rate",
                "slack_active_rate")
MARGIN_METRICS = ("d_safe_mean", "d_safe_p50", "d_safe_p95", "v_closing_mean", "v_closing_p50", "v_closing_p95",
                  "v_closing_frac_zero_bin")
IDENTITY_KEYS = ("completeness_final", "collision_pair_steps", "min_sep_overall_m", "p5_sep_worst_step_m",
                 "cbf_intervention_rate", "slack_active_rate")


def base_cfg():
    c = copy.deepcopy(yaml.safe_load(open(BASE)))
    c["matmul_precision"] = PRECISION
    return c


def cells():
    """name -> (arm, cfg)."""
    out = {}
    for k in KS:
        c = base_cfg()
        c["cbf"].update(d_safe=FLOOR, margin_k=k, margin_mode="closing", margin_floor=FLOOR, margin_h=H)
        c["run_name"] = f"{RUN}/closing_k{k:.2f}"
        out[f"closing_k{k:.2f}"] = ("learned", c)
    for d in FIXED:
        c = base_cfg()
        c["cbf"]["d_safe"] = d
        c["run_name"] = f"{RUN}/fixed{d:.2f}"
        out[f"fixed{d:.2f}"] = ("learned", c)
    c = base_cfg()
    c["run_name"] = f"{RUN}/real_fixed0.55"
    out["real_fixed0.55"] = ("real", c)
    return out


def load_cell(name):
    return yaml.safe_load(open(os.path.join(CELL_DIR, f"{name}.yaml")))


def cmd_write_cells(a):
    os.makedirs(CELL_DIR, exist_ok=True)
    for name, (arm, cfg) in cells().items():
        p = os.path.join(CELL_DIR, f"{name}.yaml")
        with open(p, "w") as f:
            f.write(f"# AMEND20 cell {name} (arm {arm}): generated by experiments/amend20_closing_lockin.py from "
                    f"amend15_cells/s1.05.yaml (run_name + matmul_precision + cbf margin keys)\n")
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(p)


def run_rows(rdir, sc, seeds, d_collision, margin):
    rows, hist, prec = [], None, set()
    keys = BASE_METRICS + (MARGIN_METRICS if margin else ())
    for seed in seeds:
        z = np.load(os.path.join(rdir, f"logs_seed{seed}.npz"))
        m = json.load(open(os.path.join(rdir, f"metrics_seed{seed}.json")))
        f = safe_success({"pos": z["pos"].astype(np.float64), "pos_final": z["pos_final"].astype(np.float64)},
                         sc, d_collision)
        f.update({k: m[k] for k in keys[3:]})
        assert abs(f["completeness"] - m["completeness_final"]) < 1e-9
        prec.add(m.get("matmul_precision"))
        if margin:
            h = np.asarray(m["v_closing_hist"], np.int64)
            hist = h if hist is None else hist + h
        rows.append(f | {"macro_cache": m["macro_cache"]})
    out = {k: ci([r[k] for r in rows]) for k in keys}
    out |= {"macro_cache": sorted({r["macro_cache"] for r in rows}), "matmul_precision": sorted(map(str, prec))}
    if margin:
        out |= {"v_closing_hist_all_seeds": hist.tolist(), "v_closing_hist_bin_mps": m["v_closing_hist_bin_mps"]}
    return out


def diff_ci(a, b, n=10_000, seed=0):
    """mean(a) - mean(b) with an unpaired seed-level bootstrap 95% CI (each group resampled over its seeds)."""
    a, b = np.asarray(a, float), np.asarray(b, float)
    rng = np.random.default_rng(seed)
    d = rng.choice(a, (n, a.size)).mean(1) - rng.choice(b, (n, b.size)).mean(1)
    return {"diff": float(a.mean() - b.mean()), "ci95": [float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))]}


def sha256(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def cmd_report(a):
    sha = sha256(os.path.join(ROOT, WEIGHTS))
    sc = build_scenario(yaml.safe_load(open(BASE)), 100)
    out = {"d_collision": a.d_collision, "seeds": a.seeds, "gate_width": sc.gate_width, "matmul_precision": PRECISION,
           "floor": FLOOR, "h_s": H, "aneks_sha256": sha256(ANEKS), "weights": WEIGHTS, "weights_sha256": sha,
           "weights_sha256_matches_record": sha == WEIGHTS_SHA256, "ci": "seed-level (cluster) bootstrap, 10k, 95%",
           "rows": {}}
    for name, (arm, _) in cells().items():
        rdir = os.path.join(ROOT, "results", load_cell(name)["run_name"], arm)
        out["rows"][name] = run_rows(rdir, sc, a.seeds, a.d_collision, margin=name.startswith("closing"))
    # Q1: closing k=0.50 vs each fixed reference on safe-success (difference + bootstrap CI, CI-separation flag)
    q1 = {}
    c = out["rows"]["closing_k0.50"]["safe_success"]
    for d in FIXED:
        f = out["rows"][f"fixed{d:.2f}"]["safe_success"]
        q1[f"closing_k0.50_minus_fixed{d:.2f}"] = diff_ci(c["per_seed"], f["per_seed"]) | {
            "closing_ci_lo_above_fixed_ci_hi": c["ci95"][0] > f["ci95"][1]}
    q1["closing_k0.50_mean_above_both_fixed"] = all(c["mean"] > out["rows"][f"fixed{d:.2f}"]["safe_success"]["mean"]
                                                    for d in FIXED)
    q1["difference_ci_excludes_0_vs_both_fixed"] = all(q1[f"closing_k0.50_minus_fixed{d:.2f}"]["ci95"][0] > 0
                                                       for d in FIXED)
    out["Q1"] = q1
    # aneks §1: real under highest vs amend15 real (default precision), seeds 0-4
    ids = {}
    for seed in [s for s in a.seeds if s < 5]:
        m15 = json.load(open(os.path.join(AMEND15_S105_REAL, f"metrics_seed{seed}.json")))
        m20 = json.load(open(os.path.join(ROOT, "results", RUN, "real_fixed0.55", "real", f"metrics_seed{seed}.json")))
        ids[seed] = {k: [m15[k], m20[k]] for k in IDENTITY_KEYS}
    out["real_highest_vs_amend15_real_default"] = {"per_seed_[amend15,amend20]": ids,
                                                   "all_equal": all(v[0] == v[1] for r in ids.values()
                                                                    for v in r.values())}
    os.makedirs(RES, exist_ok=True)
    json.dump(out, open(os.path.join(RES, "report.json"), "w"), indent=1)

    fmt = lambda x: f"{x['mean']:.3f} [{x['ci95'][0]:.3f},{x['ci95'][1]:.3f}]"
    keys = BASE_METRICS + MARGIN_METRICS
    print(f"\nAMEND20 s=1.05, precision={PRECISION}, seeds {a.seeds} (mean [95% seed-bootstrap CI])\n" + f"{'row':18s}"
          + "".join(f"{k:>24s}" for k in keys))
    for name, r in out["rows"].items():
        print(f"{name:18s}" + "".join(f"{fmt(r[k]) if k in r else '—':>24s}" for k in keys))
    print("\nQ1:", json.dumps(q1, indent=1))
    print("real highest == amend15 real default (seeds 0-4):", out["real_highest_vs_amend15_real_default"]["all_equal"])
    print("precision logged per row:", {n: r["matmul_precision"] for n, r in out["rows"].items()})
    print("aneks sha256:", out["aneks_sha256"])
    print("weights sha256:", sha, "matches record:", sha == WEIGHTS_SHA256)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["write-cells", "report"])
    ap.add_argument("--d_collision", type=float, default=0.30)
    ap.add_argument("--seeds", type=int, nargs="+", default=SEEDS)
    a = ap.parse_args()
    {"write-cells": cmd_write_cells, "report": cmd_report}[a.cmd](a)


if __name__ == "__main__":
    main()
