"""Amendment-17: staleness-aware adaptive CBF margin (method v1), first validation run.
Base = amend15 cell s=1.05 (experiments/amend15_cells/s1.05.yaml, gate 2.309). CONTROLLER CHANGE: with cbf.margin_k set,
the per-pair CBF safe distance is d_safe_ij = min(D_COLLISION + k * |v_hat_ij| * age_j, margin_d_max)
(env/rollout.py + compensation.perception.staleness_and_rel_velocity + control.cbf). cbf.margin_k absent = the old
constant-d_safe controller, unchanged. d_safe / margin are not in the macro cache key -> the s=1.05 Phi/m* cache is
reused.

    python -m experiments.amend17_adaptive_margin write-cells   # experiments/amend17_cells/{k*,san_*}.yaml
    python -m experiments.amend17_adaptive_margin sanity        # k=0 vs constant d_safe=0.30, seed 0 -> sanity_k0.json
    python -m experiments.amend17_adaptive_margin report [--d_collision 0.30] [--seeds 0 1 2 3 4]

Rollouts:
    python -m experiments.ladder --config experiments/amend17_cells/<cell>.yaml --mode eval --arm <arm>
        --weights results/ladder_fargoal_N100/predictor_weights.npz --seeds <seed>
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os

import numpy as np
import yaml

from experiments.amend15_density_sweep import WEIGHTS, WEIGHTS_SHA256, ci, safe_success
from experiments.smoke import ROOT, build_scenario

BASE = os.path.join(ROOT, "experiments", "amend15_cells", "s1.05.yaml")
CELL_DIR = os.path.join(ROOT, "experiments", "amend17_cells")
RUN = "amend17_adaptive_margin_N100"
RES = os.path.join(ROOT, "results", RUN)
ANEKS = os.path.join(ROOT, "prereg", "prereg_projectA_amend17_adaptive_margin.md")
AMEND16_REPORT = os.path.join(ROOT, "results", "amend16_gate_diagnostic_N100", "report.json")
D_COLLISION_CFG, D_MAX = 0.30, 1.5
KS = [1.0, 1.5, 2.0]
ARMS = ["real", "learned"]
METRICS = ("safe_success", "completeness", "ever_collided", "p5_sep_worst_step_m", "cbf_intervention_rate",
           "slack_active_rate", "d_safe_mean", "d_safe_p50", "d_safe_p95")
SANITY_KEYS = ("completeness_final", "collision_pair_steps", "min_sep_overall_m", "p5_sep_worst_step_m",
               "cbf_intervention_rate", "slack_active_rate")


def base_cfg():
    return copy.deepcopy(yaml.safe_load(open(BASE)))


def cells():
    """k*: adaptive margin sweep; san_k0 / san_const: the k=0 sanity pair (both nominally d_safe = 0.30 everywhere)."""
    out = {}
    for k in KS:
        c = base_cfg()
        c["cbf"].update(d_safe=D_COLLISION_CFG, margin_k=k, margin_d_max=D_MAX)
        c["run_name"] = f"{RUN}/k{k:.2f}"
        out[f"k{k:.2f}"] = c
    c = base_cfg()
    c["cbf"].update(d_safe=D_COLLISION_CFG, margin_k=0.0, margin_d_max=D_MAX)
    c["run_name"] = f"{RUN}/sanity/k0"
    out["san_k0"] = c
    c = base_cfg()
    c["cbf"].update(d_safe=D_COLLISION_CFG)
    c["run_name"] = f"{RUN}/sanity/const0.30"
    out["san_const"] = c
    return out


def load_cell(name):
    return yaml.safe_load(open(os.path.join(CELL_DIR, f"{name}.yaml")))


def cmd_write_cells(a):
    os.makedirs(CELL_DIR, exist_ok=True)
    for name, cfg in cells().items():
        p = os.path.join(CELL_DIR, f"{name}.yaml")
        with open(p, "w") as f:
            f.write(f"# AMEND17 cell {name}: generated by experiments/amend17_adaptive_margin.py from "
                    f"amend15_cells/s1.05.yaml (run_name + cbf.d_safe / cbf.margin_k / cbf.margin_d_max)\n")
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(p)


def run_dir(cell, arm):
    return os.path.join(ROOT, "results", load_cell(cell)["run_name"], arm)


def run_rows(rdir, sc, seeds, d_collision):
    rows = []
    for seed in seeds:
        z = np.load(os.path.join(rdir, f"logs_seed{seed}.npz"))
        m = json.load(open(os.path.join(rdir, f"metrics_seed{seed}.json")))
        f = safe_success({"pos": z["pos"].astype(np.float64), "pos_final": z["pos_final"].astype(np.float64)},
                         sc, d_collision)
        f.update({k: m[k] for k in METRICS[3:]})
        f["macro_cache"] = m["macro_cache"]
        assert abs(f["completeness"] - m["completeness_final"]) < 1e-9
        rows.append(f)
    return {k: ci([r[k] for r in rows]) for k in METRICS} | {"macro_cache": sorted({r["macro_cache"] for r in rows})}


def cmd_sanity(a):
    """k=0 adaptive vs constant d_safe=0.30, seed 0, both arms: every logged array compared element-wise."""
    out = {}
    for arm in ARMS:
        za = np.load(os.path.join(run_dir("san_k0", arm), "logs_seed0.npz"))
        zb = np.load(os.path.join(run_dir("san_const", arm), "logs_seed0.npz"))
        ma = json.load(open(os.path.join(run_dir("san_k0", arm), "metrics_seed0.json")))
        mb = json.load(open(os.path.join(run_dir("san_const", arm), "metrics_seed0.json")))
        common = sorted(set(za.files) & set(zb.files))
        arr = {}
        for k in common:
            x, y = np.asarray(za[k], np.float64), np.asarray(zb[k], np.float64)
            arr[k] = {"bit_equal": bool(np.array_equal(za[k], zb[k])),
                      "max_abs_diff": float(np.nanmax(np.abs(x - y))) if x.size else 0.0}
        h = np.asarray(za["d_safe_hist"]).sum(0) if "d_safe_hist" in za.files else None
        out[arm] = {"arrays_compared": len(common), "only_in_k0": sorted(set(za.files) - set(zb.files)),
                    "all_common_arrays_bit_equal": all(v["bit_equal"] for v in arr.values()),
                    "arrays": arr, "metrics_[k0,const]": {k: [ma[k], mb[k]] for k in SANITY_KEYS},
                    "k0_d_safe_rows_off_0.30_bin": int(h[1:].sum()) if h is not None else None,
                    "k0_d_safe_mean_p50_p95": [ma["d_safe_mean"], ma["d_safe_p50"], ma["d_safe_p95"]]}
        print(arm, json.dumps({k: v for k, v in out[arm].items() if k != "arrays"}), flush=True)
    os.makedirs(RES, exist_ok=True)
    json.dump(out, open(os.path.join(RES, "sanity_k0.json"), "w"), indent=1)
    return out


def sha256(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def cmd_report(a):
    sha = sha256(os.path.join(ROOT, WEIGHTS))
    sc = build_scenario(base_cfg(), 100)
    r16 = json.load(open(AMEND16_REPORT))
    ref = {"learned@0.55 (amend15)": r16["part1_reference_amend15"]["learned@0.55"],
           "real_robust@1.90 (amend16)": r16["part1_robust_margin"]["1.90"],
           "real@0.55 (amend15)": r16["part1_reference_amend15"]["real@0.55"]}
    out = {"d_collision": a.d_collision, "seeds": a.seeds, "gate_width": sc.gate_width, "d_max": D_MAX,
           "aneks_sha256": sha256(ANEKS), "weights": WEIGHTS, "weights_sha256": sha,
           "weights_sha256_matches_record": sha == WEIGHTS_SHA256, "adaptive_margin": {},
           "reference_rows_reused": ref}
    for k in KS:
        out["adaptive_margin"][f"{k:.2f}"] = {arm: run_rows(run_dir(f"k{k:.2f}", arm), sc, a.seeds, a.d_collision)
                                              for arm in ARMS}
    p = os.path.join(RES, "sanity_k0.json")
    out["sanity_k0"] = json.load(open(p)) if os.path.exists(p) else None
    os.makedirs(RES, exist_ok=True)
    json.dump(out, open(os.path.join(RES, "report.json"), "w"), indent=1)

    fmt = lambda x: "—" if x is None or x.get("mean") is None else f"{x['mean']:.3f} [{x['ci95'][0]:.3f},{x['ci95'][1]:.3f}]"
    keys = METRICS
    print("\nAMEND17 adaptive margin, s=1.05 (mean [95% seed-bootstrap CI])\n" + f"{'row':28s}"
          + "".join(f"{k:>24s}" for k in keys))
    for k, arms in out["adaptive_margin"].items():
        for arm, r in arms.items():
            print(f"{'k=' + k + ' ' + arm:28s}" + "".join(f"{fmt(r[m]):>24s}" for m in keys))
    for n, r in ref.items():
        print(f"{'ref ' + n:28s}" + "".join(f"{fmt(r.get(m)):>24s}" for m in keys))
    s = out["sanity_k0"]
    print("\nsanity k=0 all arrays bit-equal:", {arm: s[arm]["all_common_arrays_bit_equal"] for arm in ARMS} if s else None)
    print("aneks sha256:", out["aneks_sha256"])
    print("weights sha256:", sha, "matches record:", sha == WEIGHTS_SHA256)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["write-cells", "sanity", "report"])
    ap.add_argument("--d_collision", type=float, default=0.30)
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    a = ap.parse_args()
    {"write-cells": cmd_write_cells, "sanity": cmd_sanity, "report": cmd_report}[a.cmd](a)


if __name__ == "__main__":
    main()
