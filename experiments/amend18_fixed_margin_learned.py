"""Amendment-18: fixed (constant) d_safe sweep on the learned arm at s=1.05 (gate 2.309). Measurement only; the
constant-d_safe CBF path is unchanged. Base = experiments/amend15_cells/s1.05.yaml; s=1.05 cache reused.

    python -m experiments.amend18_fixed_margin_learned write-cells   # experiments/amend18_cells/d*.yaml
    python -m experiments.amend18_fixed_margin_learned report [--d_collision 0.30] [--seeds 0 1 2 3 4]

Rollouts:
    python -m experiments.ladder --config experiments/amend18_cells/<cell>.yaml --mode eval --arm learned
        --weights results/ladder_fargoal_N100/predictor_weights.npz --seeds <seed>
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os

import yaml

from experiments.amend15_density_sweep import WEIGHTS, WEIGHTS_SHA256
from experiments.amend16_gate_diagnostic import run_rows
from experiments.smoke import ROOT, build_scenario

BASE = os.path.join(ROOT, "experiments", "amend15_cells", "s1.05.yaml")
CELL_DIR = os.path.join(ROOT, "experiments", "amend18_cells")
RUN = "amend18_fixed_margin_learned_N100"
RES = os.path.join(ROOT, "results", RUN)
ANEKS = os.path.join(ROOT, "prereg", "prereg_projectA_amend18_fixed_margin_learned.md")
AMEND15_S105_LEARNED = os.path.join(ROOT, "results", "density_sweep_amend15_N100", "s1.05", "learned")
AMEND16_REPORT = os.path.join(ROOT, "results", "amend16_gate_diagnostic_N100", "report.json")
D_SAFES = [0.55, 0.70, 0.85, 1.00]
KEYS = ("safe_success", "completeness", "ever_collided", "p5_sep_worst_step_m", "cbf_intervention_rate",
        "slack_active_rate")
IDENTITY_KEYS = ("completeness_final", "collision_pair_steps", "min_sep_overall_m", "p5_sep_worst_step_m",
                 "cbf_intervention_rate", "slack_active_rate")


def cells():
    out = {}
    for d in D_SAFES:
        c = copy.deepcopy(yaml.safe_load(open(BASE)))
        c["cbf"]["d_safe"] = d
        c["run_name"] = f"{RUN}/d{d:.2f}"
        out[f"d{d:.2f}"] = c
    return out


def cmd_write_cells(a):
    os.makedirs(CELL_DIR, exist_ok=True)
    for name, cfg in cells().items():
        p = os.path.join(CELL_DIR, f"{name}.yaml")
        with open(p, "w") as f:
            f.write(f"# AMEND18 cell {name}: generated by experiments/amend18_fixed_margin_learned.py from "
                    f"amend15_cells/s1.05.yaml (run_name + cbf.d_safe)\n")
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(p)


def sha256(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def cmd_report(a):
    sha = sha256(os.path.join(ROOT, WEIGHTS))
    sc = build_scenario(yaml.safe_load(open(BASE)), 100)
    out = {"d_collision": a.d_collision, "seeds": a.seeds, "gate_width": sc.gate_width, "arm": "learned",
           "aneks_sha256": sha256(ANEKS), "weights": WEIGHTS, "weights_sha256": sha,
           "weights_sha256_matches_record": sha == WEIGHTS_SHA256, "fixed_margin_learned": {},
           "reference_rows_reused": {"learned@0.55 (amend15)":
                                     json.load(open(AMEND16_REPORT))["part1_reference_amend15"]["learned@0.55"]}}
    for d in D_SAFES:
        rdir = os.path.join(ROOT, "results", RUN, f"d{d:.2f}", "learned")
        out["fixed_margin_learned"][f"{d:.2f}"] = run_rows(rdir, sc, a.seeds, a.d_collision)
    ids = {}
    for seed in a.seeds:
        m15 = json.load(open(os.path.join(AMEND15_S105_LEARNED, f"metrics_seed{seed}.json")))
        m18 = json.load(open(os.path.join(ROOT, "results", RUN, "d0.55", "learned", f"metrics_seed{seed}.json")))
        ids[seed] = {k: [m15[k], m18[k]] for k in IDENTITY_KEYS}
    out["identity_d0.55_vs_amend15_learned"] = {"per_seed_[amend15,amend18]": ids,
                                                "all_equal": all(v[0] == v[1] for r in ids.values() for v in r.values())}
    os.makedirs(RES, exist_ok=True)
    json.dump(out, open(os.path.join(RES, "report.json"), "w"), indent=1)

    fmt = lambda x: f"{x['mean']:.3f} [{x['ci95'][0]:.3f},{x['ci95'][1]:.3f}]"
    print("\nAMEND18 fixed d_safe, learned, s=1.05 (mean [95% seed-bootstrap CI])\n" + f"{'row':26s}"
          + "".join(f"{k:>24s}" for k in KEYS))
    for d, r in out["fixed_margin_learned"].items():
        print(f"{'d_safe ' + d:26s}" + "".join(f"{fmt(r[k]):>24s}" for k in KEYS))
    for n, r in out["reference_rows_reused"].items():
        print(f"{'ref ' + n:26s}" + "".join(f"{fmt(r[k]):>24s}" for k in KEYS))
    print("identity d0.55 == amend15 learned:", out["identity_d0.55_vs_amend15_learned"]["all_equal"])
    print("aneks sha256:", out["aneks_sha256"])
    print("weights sha256:", sha, "matches record:", sha == WEIGHTS_SHA256)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["write-cells", "report"])
    ap.add_argument("--d_collision", type=float, default=0.30)
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    a = ap.parse_args()
    {"write-cells": cmd_write_cells, "report": cmd_report}[a.cmd](a)


if __name__ == "__main__":
    main()
